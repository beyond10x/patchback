#![forbid(unsafe_code)]
//! Generates the derivable part of the Patchback documentation site under `website/`, checks it
//! for drift, and binds a built site to its source commit. The site build itself is Docusaurus.
//!
//! Everything generated comes from the repository: the domain reference pages from
//! `ess generate --kind docs`, the contract explorer's document from `ess generate --kind docs-ir`,
//! one `b10x-domain-graph/1` document per domain and one for the whole model from
//! `ess specify compile`, and the status data and page from [`status::CAPABILITIES`].
mod graph;
mod reference;
mod status;

use std::{
    collections::BTreeMap,
    ffi::OsStr,
    fs,
    path::{Path, PathBuf},
    process::{Command, ExitCode},
};

use clap::{Parser, Subcommand};

type Result<T> = std::result::Result<T, String>;

/// The first front-matter line of every generated page.
pub const FRONT_MATTER_HEADER: &str = "# generated by patchback-docs, do not edit";

/// Where the ESS reference pages land, relative to the repository root.
const ESS_REFERENCE: &str = "website/docs/reference/ess";
/// Where the domain graphs and the contract document land, relative to the repository root.
const ESS_DATA: &str = "website/data/ess";
/// The whole-model graph, under `ESS_DATA`.
const SYSTEM_GRAPH: &str = "patchback.domain-graph.json";
/// The `ess-docs/1` document the contract explorer renders, under `ESS_DATA`.
const CONTRACT_DOCUMENT: &str = "patchback.ess-docs.json";
/// Every documentation page, generated or written by hand, relative to the repository root.
const DOCS: &str = "website/docs";
/// The landing page's content, relative to the repository root.
const LANDING: &str = "website/product.json";
/// The route the site is served under.
const BASE_URL: &str = "/patchback/";

/// Strings no published page may contain: local paths and planning-store ids.
const PRIVATE: &[&str] = &[
    "/home/",
    "/Users/",
    "story:",
    "epic:",
    "task:",
    "initiative:",
];

#[derive(Parser)]
#[command(about = "Generate and check the derived pages of the Patchback documentation site")]
struct Cli {
    #[command(subcommand)]
    command: Action,
}

#[derive(Subcommand)]
enum Action {
    /// Regenerate the derived files under website/, or check them for drift.
    Generate {
        /// Write nothing; fail when a generated file is missing, stale or hand-edited.
        #[arg(long)]
        check: bool,
        /// Repository root.
        #[arg(long, default_value = ".")]
        root: PathBuf,
        /// The `ess` executable.
        #[arg(long, default_value = "ess")]
        ess: PathBuf,
    },
    /// Bind a built site to its source commit: write `.well-known/b10x-site.json` into it.
    Provenance {
        /// The built site, `website/build`.
        #[arg(long)]
        site: PathBuf,
        /// The full Git revision the site was built from.
        #[arg(long)]
        commit: String,
    },
}

/// Whether `line` matches `^:::[a-z]+ +\S`: an admonition whose title is not in brackets, which
/// Docusaurus prints as raw text.
fn is_raw_admonition(line: &str) -> bool {
    let Some(rest) = line.strip_prefix(":::") else {
        return false;
    };
    let kind = rest.bytes().take_while(u8::is_ascii_lowercase).count();
    let rest = &rest[kind..];
    let spaces = rest.bytes().take_while(|b| *b == b' ').count();
    kind > 0
        && spaces > 0
        && rest[spaces..]
            .chars()
            .next()
            .is_some_and(|c| !c.is_whitespace())
}

fn io(context: impl std::fmt::Display) -> impl FnOnce(std::io::Error) -> String {
    move |e| format!("{context}: {e}")
}

/// Directory entries of `dir`, sorted by path.
fn sorted_entries(dir: &Path) -> Result<Vec<fs::DirEntry>> {
    let mut entries = fs::read_dir(dir)
        .map_err(io(dir.display()))?
        .collect::<std::io::Result<Vec<_>>>()
        .map_err(io(dir.display()))?;
    entries.sort_by_key(|entry| entry.path());
    Ok(entries)
}

/// Every Markdown and MDX page under `dir`, recursively.
fn pages_under(dir: &Path) -> Result<Vec<PathBuf>> {
    let mut found = Vec::new();
    for entry in sorted_entries(dir)? {
        let path = entry.path();
        if path.is_dir() {
            found.extend(pages_under(&path)?);
        } else if path
            .extension()
            .is_some_and(|ext| ext == "md" || ext == "mdx")
        {
            found.push(path);
        }
    }
    Ok(found)
}

/// `file:line` of every raw admonition title in the pages under `dir`.
fn raw_admonitions(dir: &Path) -> Result<Vec<String>> {
    let mut found = Vec::new();
    for path in pages_under(dir)? {
        let text = fs::read_to_string(&path).map_err(io(path.display()))?;
        for (n, line) in text.lines().enumerate() {
            if is_raw_admonition(line) {
                found.push(format!("{}:{}", path.display(), n + 1));
            }
        }
    }
    Ok(found)
}

/// `file:line: string` of every private string in `files`.
fn private_strings(files: &[PathBuf]) -> Result<Vec<String>> {
    let mut found = Vec::new();
    for path in files {
        let text = fs::read_to_string(path).map_err(io(path.display()))?;
        for (n, line) in text.lines().enumerate() {
            for private in PRIVATE.iter().filter(|p| line.contains(*p)) {
                found.push(format!("{}:{}: {private}", path.display(), n + 1));
            }
        }
    }
    Ok(found)
}

/// The project-site publication record for one build of the `/patchback/` site.
fn site_manifest(commit: &str) -> Result<String> {
    if commit.len() != 40
        || !commit.bytes().all(|b| b.is_ascii_hexdigit())
        || commit == "0".repeat(40)
    {
        return Err("commit must be a nonzero full Git revision".into());
    }
    Ok(format!(
        "{{\n  \"baseUrl\": \"{BASE_URL}\",\n  \"commit\": \"{commit}\",\n  \"repository\": \"patchback\",\n  \"schema\": \"b10x-project-site/v1\"\n}}"
    ))
}

fn write_provenance(site: &Path, commit: &str) -> Result<()> {
    let manifest = site_manifest(commit)?;
    if !site.join("index.html").is_file() {
        return Err(format!("{} holds no built site", site.display()));
    }
    let well_known = site.join(".well-known");
    fs::create_dir_all(&well_known).map_err(io(well_known.display()))?;
    fs::write(well_known.join("b10x-site.json"), manifest).map_err(io("site provenance"))?;
    fs::write(site.join(".nojekyll"), "").map_err(io(".nojekyll"))?;
    Ok(())
}

/// Files keyed by file name.
type Pages = BTreeMap<String, String>;

/// The generated files of one directory.
struct Output {
    /// Relative to the repository root.
    dir: &'static str,
    files: Pages,
    /// Whether the directory holds generated files only: a file nobody generates is drift, and
    /// `generate` empties the directory before writing.
    exclusive: bool,
}

/// Run `ess` with `args` in `cwd`, the specification directory: an `ess` that dispatches to the
/// release `ess-inputs.yaml` requires looks for that file in its working directory.
fn run(ess: &Path, cwd: &Path, args: &[&OsStr]) -> Result<Vec<u8>> {
    let output = Command::new(ess)
        .current_dir(cwd)
        .args(args)
        .output()
        .map_err(io(format!("running {}", ess.display())))?;
    if !output.status.success() {
        return Err(format!(
            "{} {} failed: {}",
            ess.display(),
            args.iter()
                .map(|arg| arg.to_string_lossy())
                .collect::<Vec<_>>()
                .join(" "),
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    Ok(output.stdout)
}

/// `ess generate --kind <kind>` over `spec` into `out`.
fn ess_generate(ess: &Path, spec: &Path, kind: &str, out: &Path) -> Result<()> {
    let out = std::path::absolute(out).map_err(io(out.display()))?;
    run(
        ess,
        spec,
        &[
            "generate".as_ref(),
            "--path".as_ref(),
            ".".as_ref(),
            "--kind".as_ref(),
            kind.as_ref(),
            "--out".as_ref(),
            out.as_os_str(),
            "--strict-requires".as_ref(),
        ],
    )
    .map(drop)
}

/// The domain pages and the index, from `ess generate --kind docs` in `scratch`.
fn reference_pages(ess: &Path, spec: &Path, scratch: &Path, graphs: &Pages) -> Result<Pages> {
    let out = scratch.join("docs");
    ess_generate(ess, spec, "docs", &out)?;
    let mut pages = Pages::new();
    let mut index = Vec::new();
    for entry in sorted_entries(&out.join("docs/domains"))? {
        let name = entry.file_name().to_string_lossy().into_owned();
        let Some(stem) = name.strip_suffix(".md") else {
            continue;
        };
        let graph = format!("{stem}.domain-graph.json");
        if !graphs.contains_key(&graph) {
            return Err(format!(
                "ess page {name} has no domain in the compiled model"
            ));
        }
        let source = fs::read_to_string(entry.path()).map_err(io(entry.path().display()))?;
        let (title, summary, page) = reference::domain_page(&source)?;
        index.push(reference::DomainEntry {
            page: name.clone(),
            graph,
            title,
            summary,
        });
        pages.insert(name, page);
    }
    if index.is_empty() {
        return Err("ess generated no domain pages".into());
    }
    if index.len() != graphs.len() {
        return Err(format!(
            "ess generated {} domain pages for {} domains",
            index.len(),
            graphs.len()
        ));
    }
    pages.insert(
        "index.mdx".to_owned(),
        reference::index_page(SYSTEM_GRAPH, &index),
    );
    Ok(pages)
}

/// The `ess-docs/1` document of `ess generate --kind docs-ir` in `scratch`, compacted: the
/// explorer page imports it whole, so its size is the page's size.
fn contract_document(ess: &Path, spec: &Path, scratch: &Path) -> Result<String> {
    let out = scratch.join("docs-ir");
    ess_generate(ess, spec, "docs-ir", &out)?;
    let path = out.join("docs-ir/document.json");
    let text = fs::read_to_string(&path).map_err(io(path.display()))?;
    compact_contract(&text)
}

/// Check that `text` is an `ess-docs/1` document and write it without whitespace.
fn compact_contract(text: &str) -> Result<String> {
    let document: serde_json::Value =
        serde_json::from_str(text).map_err(|e| format!("parsing the ess-docs document: {e}"))?;
    if document["format"] != "ess-docs/1" {
        return Err(format!(
            "ess docs-ir wrote format {}, not ess-docs/1",
            document["format"]
        ));
    }
    serde_json::to_string(&document)
        .map(|text| text + "\n")
        .map_err(|e| e.to_string())
}

fn pretty(value: &serde_json::Value) -> Result<String> {
    serde_json::to_string_pretty(value)
        .map(|text| text + "\n")
        .map_err(|e| e.to_string())
}

/// Run `ess` and build every generated file of the site that comes from `spec/`.
fn ess_outputs(root: &Path, ess: &Path) -> Result<Vec<Output>> {
    let spec = root.join("spec");
    let compiled = run(
        ess,
        &spec,
        &[
            "specify".as_ref(),
            "compile".as_ref(),
            "--path".as_ref(),
            ".".as_ref(),
            "--format".as_ref(),
            "json".as_ref(),
        ],
    )?;
    let model: serde_json::Value = serde_json::from_slice(&compiled)
        .map_err(|e| format!("parsing the compiled ESS model: {e}"))?;
    let mut graphs = Pages::new();
    for (domain, graph) in graph::domain_graphs(&model)? {
        let name = format!("{}.domain-graph.json", domain.replace('.', "-"));
        graphs.insert(name, pretty(&graph)?);
    }

    let scratch = std::env::temp_dir().join(format!("patchback-docs-{}", std::process::id()));
    if scratch.exists() {
        fs::remove_dir_all(&scratch).map_err(io(scratch.display()))?;
    }
    let generated = reference_pages(ess, &spec, &scratch, &graphs).and_then(|pages| {
        let contract = contract_document(ess, &spec, &scratch)?;
        Ok((pages, contract))
    });
    let _ = fs::remove_dir_all(&scratch);
    let (mut pages, contract) = generated?;
    pages.insert(
        "explorer.mdx".to_owned(),
        reference::explorer_page(CONTRACT_DOCUMENT),
    );

    let mut data = graphs;
    data.insert(CONTRACT_DOCUMENT.to_owned(), contract);
    if data
        .insert(
            SYSTEM_GRAPH.to_owned(),
            pretty(&graph::system_graph(&model)?)?,
        )
        .is_some()
    {
        return Err(format!("a domain's graph is named {SYSTEM_GRAPH}"));
    }
    Ok(vec![
        Output {
            dir: ESS_REFERENCE,
            files: pages,
            exclusive: true,
        },
        Output {
            dir: ESS_DATA,
            files: data,
            exclusive: true,
        },
    ])
}

/// The files that come from the crate itself: the status data and the status page.
fn status_outputs(root: &Path) -> Result<(Vec<Output>, Vec<String>)> {
    let (data, warnings) = status::document(root)?;
    Ok((
        vec![
            Output {
                dir: status::DIR,
                files: Pages::from([(status::FILE.to_owned(), data)]),
                exclusive: false,
            },
            Output {
                dir: DOCS,
                files: Pages::from([(
                    status::PAGE.to_owned(),
                    status::page(status::CAPABILITIES, status::AS_OF),
                )]),
                exclusive: false,
            },
        ],
        warnings,
    ))
}

/// Every difference between the expected files and the files in `dir`. Subdirectories are not
/// compared; a stray file counts only in an exclusive directory.
fn drift(expected: &Pages, dir: &Path, exclusive: bool) -> Result<Vec<String>> {
    let mut actual = Pages::new();
    if dir.exists() {
        for entry in sorted_entries(dir)? {
            if entry.path().is_dir() {
                continue;
            }
            let name = entry.file_name().to_string_lossy().into_owned();
            let text = fs::read_to_string(entry.path()).map_err(io(entry.path().display()))?;
            actual.insert(name, text);
        }
    }
    let mut problems = Vec::new();
    for (name, content) in expected {
        match actual.get(name) {
            None => problems.push(format!("missing {name}")),
            Some(found) if found != content => problems.push(format!("stale or edited {name}")),
            Some(_) => {}
        }
    }
    if exclusive {
        for name in actual.keys().filter(|name| !expected.contains_key(*name)) {
            problems.push(format!("not generated {name}"));
        }
    }
    Ok(problems)
}

fn write(root: &Path, output: &Output) -> Result<()> {
    let dir = root.join(output.dir);
    if output.exclusive && dir.exists() {
        fs::remove_dir_all(&dir).map_err(io(dir.display()))?;
    }
    fs::create_dir_all(&dir).map_err(io(dir.display()))?;
    for (name, content) in &output.files {
        fs::write(dir.join(name), content).map_err(io(dir.join(name).display()))?;
    }
    Ok(())
}

fn generate(root: &Path, ess: &Path, check: bool) -> Result<()> {
    let mut outputs = ess_outputs(root, ess)?;
    let (status, warnings) = status_outputs(root)?;
    outputs.extend(status);
    for output in &outputs {
        if check {
            let problems = drift(&output.files, &root.join(output.dir), output.exclusive)?;
            if !problems.is_empty() {
                return Err(format!(
                    "{} has drifted ({}); run `task docs-generate`",
                    output.dir,
                    problems.join(", ")
                ));
            }
            println!(
                "{}: {} generated files current",
                output.dir,
                output.files.len()
            );
        } else {
            write(root, output)?;
            println!("{}: wrote {} files", output.dir, output.files.len());
        }
    }
    for warning in warnings {
        eprintln!("patchback-docs: warning: {warning}");
    }
    let docs = root.join(DOCS);
    let raw = raw_admonitions(&docs)?;
    if !raw.is_empty() {
        return Err(format!(
            "raw admonition titles (write `:::kind[Title]`): {}",
            raw.join(", ")
        ));
    }
    println!("{DOCS}: no raw admonition titles");
    let mut published = pages_under(&docs)?;
    published.push(root.join(LANDING));
    let private = private_strings(&published)?;
    if !private.is_empty() {
        return Err(format!(
            "local paths or planning ids in published pages: {}",
            private.join(", ")
        ));
    }
    println!("{DOCS}: no local paths or planning ids");
    Ok(())
}

fn main() -> ExitCode {
    let result = match Cli::parse().command {
        Action::Generate { check, root, ess } => generate(&root, &ess, check),
        Action::Provenance { site, commit } => write_provenance(&site, &commit)
            .map(|()| println!("{}: bound to {commit}", site.display())),
    };
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("patchback-docs: {e}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn scratch(name: &str) -> PathBuf {
        let dir =
            std::env::temp_dir().join(format!("patchback-docs-test-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn the_contract_document_must_be_ess_docs_and_is_compacted() {
        let compact =
            compact_contract("{\n  \"format\": \"ess-docs/1\",\n  \"pages\": []\n}").unwrap();
        assert_eq!(compact, "{\"format\":\"ess-docs/1\",\"pages\":[]}\n");
        assert!(compact_contract("{\"format\": \"ess-docs/2\"}").is_err());
        assert!(compact_contract("not json").is_err());
    }

    #[test]
    fn provenance_names_the_commit_and_refuses_a_bad_one() {
        assert!(site_manifest("abc").is_err());
        assert!(site_manifest(&"0".repeat(40)).is_err());
        assert!(site_manifest(&"g".repeat(40)).is_err());
        let commit = "0123456789abcdef0123456789abcdef01234567";
        let site = scratch("provenance");
        assert!(write_provenance(&site, commit).is_err());
        fs::write(site.join("index.html"), "<html></html>").unwrap();
        write_provenance(&site, commit).unwrap();
        let written = fs::read_to_string(site.join(".well-known/b10x-site.json")).unwrap();
        let manifest: serde_json::Value = serde_json::from_str(&written).unwrap();
        assert_eq!(manifest["schema"], "b10x-project-site/v1");
        assert_eq!(manifest["repository"], "patchback");
        assert_eq!(manifest["commit"], commit);
        assert_eq!(manifest["baseUrl"], "/patchback/");
        assert!(site.join(".nojekyll").is_file());
        let _ = fs::remove_dir_all(&site);
    }

    #[test]
    fn raw_admonition_titles_are_found_and_bracketed_ones_pass() {
        assert!(is_raw_admonition(":::note Planned"));
        assert!(!is_raw_admonition(":::note[Planned]"));
        assert!(!is_raw_admonition(":::note"));
        assert!(!is_raw_admonition(":::"));
        let dir = scratch("admonitions");
        fs::create_dir_all(dir.join("nested")).unwrap();
        fs::write(dir.join("a.md"), "# A\n\n:::tip[Fine]\nx\n:::\n").unwrap();
        fs::write(dir.join("nested/b.mdx"), "# B\n\n:::caution Raw\nx\n:::\n").unwrap();
        let found = raw_admonitions(&dir).unwrap();
        assert_eq!(found.len(), 1);
        assert!(found[0].ends_with("nested/b.mdx:3"));
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn local_paths_and_planning_ids_are_found() {
        let dir = scratch("private");
        fs::write(dir.join("clean.md"), "# Clean\n\nRun `patchback fit`.\n").unwrap();
        let leak = concat!("# Leak\n\nSee /", "home/someone/x.\n\nepic:x\n");
        fs::write(dir.join("leak.md"), leak).unwrap();
        let found = private_strings(&[dir.join("clean.md"), dir.join("leak.md")]).unwrap();
        assert_eq!(found.len(), 2);
        assert!(found[0].ends_with("leak.md:3: /home/"));
        assert!(found[1].ends_with("leak.md:5: epic:"));
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn drift_names_missing_edited_and_stray_files_and_strays_only_when_exclusive() {
        let dir = scratch("drift");
        fs::create_dir_all(dir.join("sub")).unwrap();
        fs::write(dir.join("edited.md"), "hand edit").unwrap();
        fs::write(dir.join("stray.md"), "x").unwrap();
        fs::write(dir.join("same.md"), "same").unwrap();
        let expected = Pages::from([
            ("edited.md".to_owned(), "generated".to_owned()),
            ("missing.md".to_owned(), "generated".to_owned()),
            ("same.md".to_owned(), "same".to_owned()),
        ]);
        let mut problems = drift(&expected, &dir, true).unwrap();
        problems.sort();
        assert_eq!(
            problems,
            [
                "missing missing.md",
                "not generated stray.md",
                "stale or edited edited.md"
            ]
        );
        let mut problems = drift(&expected, &dir, false).unwrap();
        problems.sort();
        assert_eq!(
            problems,
            ["missing missing.md", "stale or edited edited.md"]
        );
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn writing_a_shared_directory_keeps_the_files_it_does_not_generate() {
        let root = scratch("shared");
        fs::create_dir_all(root.join("website/docs/guides")).unwrap();
        fs::write(root.join("website/docs/guides/x.md"), "# X\n").unwrap();
        let output = Output {
            dir: "website/docs",
            files: Pages::from([("status.mdx".to_owned(), "# Status\n".to_owned())]),
            exclusive: false,
        };
        write(&root, &output).unwrap();
        assert!(root.join("website/docs/guides/x.md").is_file());
        assert_eq!(
            fs::read_to_string(root.join("website/docs/status.mdx")).unwrap(),
            "# Status\n"
        );
        let _ = fs::remove_dir_all(&root);
    }
}
