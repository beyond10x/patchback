//! The ESS reference pages under `website/docs/reference/ess/`: the domain pages from
//! `ess generate --kind docs`, an index with one domain graph per domain, and the contract
//! explorer over `ess generate --kind docs-ir`.

/// The line every generated Markdown page carries directly after its front matter.
pub const HEADER: &str = "<!-- generated by patchback-docs, do not edit -->";
/// The same line in an MDX page, where HTML comments are not allowed.
pub const MDX_HEADER: &str = "{/* generated by patchback-docs, do not edit */}";

/// Strip the leading HTML comment `ess generate` writes, returning the rest.
fn strip_ess_banner(page: &str) -> Result<&str, String> {
    let rest = page
        .strip_prefix("<!--")
        .ok_or("ess page does not open with its provenance comment")?;
    let end = rest
        .find("-->")
        .ok_or("ess provenance comment is not closed")?;
    Ok(rest[end + 3..].trim_start_matches('\n'))
}

/// The H1 title and the first paragraph after it.
fn title_and_summary(body: &str) -> Result<(String, String), String> {
    let mut lines = body.lines();
    let title = lines
        .next()
        .and_then(|line| line.strip_prefix("# "))
        .ok_or("ess page does not open with a level-one heading")?
        .trim()
        .to_owned();
    let summary = lines
        .skip_while(|line| line.trim().is_empty())
        .take_while(|line| !line.trim().is_empty())
        .collect::<Vec<_>>()
        .join(" ");
    if summary.is_empty() {
        return Err(format!("ess page {title} has no summary"));
    }
    Ok((title, summary))
}

fn yaml_string(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

/// Front matter of a generated page: the generator line, title, label, description, position and
/// no edit link.
pub fn front_matter(title: &str, label: &str, description: &str, position: Option<u32>) -> String {
    let position = position.map_or(String::new(), |n| format!("sidebar_position: {n}\n"));
    format!(
        "---\n{}\ntitle: {}\nsidebar_label: {}\n{position}description: {}\ncustom_edit_url: null\n---\n\n",
        crate::FRONT_MATTER_HEADER,
        yaml_string(title),
        yaml_string(label),
        yaml_string(description),
    )
}

/// One domain page of `ess generate --kind docs`, rewritten as a site page: `(title, summary,
/// page)`. The level-one heading is dropped so the front matter's title heads the page.
pub fn domain_page(source: &str) -> Result<(String, String, String), String> {
    let body = strip_ess_banner(source)?;
    let (title, summary) = title_and_summary(body)?;
    let body = body
        .split_once('\n')
        .map_or("", |(_, rest)| rest)
        .trim_start_matches('\n')
        .replace(
            "[Back to the index](../index.md)",
            "[All domains](./index.mdx)",
        )
        .replace("`ess generate`", "`task docs-generate`");
    if body.contains("](../") {
        return Err(format!(
            "ess page {title} links outside the generated domain pages"
        ));
    }
    let page = front_matter(
        &format!("{title} domain"),
        &title,
        &format!("ESS reference for the {title} domain, generated from the specification."),
        None,
    ) + HEADER
        + "\n\n"
        + &body;
    Ok((title, summary, page))
}

/// One domain as the index lists it.
pub struct DomainEntry {
    pub page: String,
    pub graph: String,
    pub title: String,
    pub summary: String,
}

/// The reference index: the whole model as one graph, then one `<DomainGraph>` per domain with a
/// link to its full page.
pub fn index_page(system_graph: &str, domains: &[DomainEntry]) -> String {
    let mut page = front_matter(
        "ESS specification",
        "ESS specification",
        "The Patchback specification, domain by domain, generated from spec/ in the repository.",
        Some(10),
    ) + MDX_HEADER
        + "\n\n";
    page.push_str(&format!(
        "import systemGraph from '@site/data/ess/{system_graph}';\n"
    ));
    for (n, domain) in domains.iter().enumerate() {
        page.push_str(&format!(
            "import domainGraph{n} from '@site/data/ess/{}';\n",
            domain.graph
        ));
    }
    page.push_str("\n# ESS specification\n\n");
    page.push_str(&format!(
        "Every noun of Patchback has a typed home in an ESS domain: the patch and its graph, the \
         score of note events, audio, analysis, the dataset, the model, the fit and the \
         dependency policy. This page and the {count} domain pages below are generated from the \
         repository's `spec/` directory by `patchback-docs`: the graphs from `ess specify \
         compile`, the pages from `ess generate --kind docs`. `task check` fails when they fall \
         behind the specification.\n\n\
         The [contract explorer](./explorer.mdx) shows the whole specification in one searchable \
         view.\n\n\
         ## The whole model\n\n\
         Every entity and every relation across the domains. An arrow is a relation, labelled \
         with its name; a lifecycle lists the states an entity moves through.\n\n\
         <DomainGraph data={{systemGraph}} title=\"Patchback\" />\n",
        count = domains.len()
    ));
    for (n, domain) in domains.iter().enumerate() {
        page.push_str(&format!(
            "\n## {title}\n\n{summary}\n\n<DomainGraph data={{domainGraph{n}}} title=\"{title}\" />\n\n\
             [Read the {title} domain in full](./{file})\n",
            title = domain.title,
            summary = domain.summary,
            file = domain.page,
        ));
    }
    page
}

/// The contract explorer: Docs System's `EssContractViewer` over the `ess-docs/1` document.
pub fn explorer_page(document: &str) -> String {
    let mut page = front_matter(
        "Contract explorer",
        "Contract explorer",
        "Search and browse every entity, command, event and lifecycle of the Patchback specification.",
        Some(11),
    ) + MDX_HEADER
        + "\n\n";
    page.push_str(&format!(
        "import {{EssContractViewer}} from '@beyond10x/docs-system/ess-contract-viewer';\n\
         import contract from '@site/data/ess/{document}';\n\n\
         # Contract explorer\n\n\
         The whole specification in one searchable view: every domain, entity, command, event and \
         lifecycle, from the `ess-docs/1` document `ess generate --kind docs-ir` writes. The \
         [domain pages](./index.mdx) hold the same content page by page.\n\n\
         <EssContractViewer document={{contract}} id=\"patchback\" title=\"Patchback contracts\" \
         sourceRepository=\"https://github.com/beyond10x/patchback/tree/main/spec\" />\n"
    ));
    page
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = "<!--\ngenerated from patchback v1\ndo not edit: regenerate with `ess generate`\n-->\n\n# Patches\n\nAn editable DSP program.\nValidated before it runs.\n\n`patchback.patch` is one of patchback's bounded contexts. [Back to the index](../index.md).\n\nSee [`NoteEvent`](patchback-score.md#noteevent).\n\nDo not edit this file; regenerate it with `ess generate`.\n";

    #[test]
    fn domain_pages_carry_the_header_and_no_ess_banner() {
        let (title, summary, page) = domain_page(SAMPLE).unwrap();
        assert_eq!(title, "Patches");
        assert_eq!(summary, "An editable DSP program. Validated before it runs.");
        assert!(page.starts_with(&format!(
            "---\n{}\ntitle: \"Patches domain\"\n",
            crate::FRONT_MATTER_HEADER
        )));
        assert!(page.contains("custom_edit_url: null\n"));
        assert!(page.contains(&format!("{HEADER}\n\nAn editable DSP program.")));
        assert!(!page.contains("<!--\ngenerated from"));
        assert!(!page.contains("# Patches\n"));
        assert!(page.contains("[All domains](./index.mdx)"));
        assert!(page.contains("(patchback-score.md#noteevent)"));
        assert!(page.contains("`task docs-generate`"));
        assert!(!page.contains("`ess generate`"));
    }

    #[test]
    fn links_out_of_the_domain_set_are_refused() {
        let page = SAMPLE.replace("bounded contexts.", "bounded contexts. [x](../topology.md)");
        assert!(domain_page(&page).is_err());
    }

    #[test]
    fn index_renders_the_system_graph_and_one_graph_per_domain() {
        let page = index_page(
            "patchback.domain-graph.json",
            &[DomainEntry {
                page: "patchback-patch.md".into(),
                graph: "patchback-patch.domain-graph.json".into(),
                title: "Patches".into(),
                summary: "An editable DSP program.".into(),
            }],
        );
        assert!(page.contains(MDX_HEADER));
        assert!(
            page.contains("import systemGraph from '@site/data/ess/patchback.domain-graph.json';")
        );
        assert!(page.contains("<DomainGraph data={systemGraph} title=\"Patchback\" />"));
        assert!(page.contains(
            "import domainGraph0 from '@site/data/ess/patchback-patch.domain-graph.json';"
        ));
        assert!(page.contains("<DomainGraph data={domainGraph0} title=\"Patches\" />"));
        assert!(page.contains("[Read the Patches domain in full](./patchback-patch.md)"));
    }

    #[test]
    fn the_explorer_renders_the_contract_viewer_over_the_document() {
        let page = explorer_page("patchback.ess-docs.json");
        assert!(page.contains("title: \"Contract explorer\"\n"));
        assert!(page.contains(MDX_HEADER));
        assert!(page.contains(
            "import {EssContractViewer} from '@beyond10x/docs-system/ess-contract-viewer';"
        ));
        assert!(page.contains("import contract from '@site/data/ess/patchback.ess-docs.json';"));
        assert!(page.contains("<EssContractViewer document={contract} id=\"patchback\""));
    }
}
